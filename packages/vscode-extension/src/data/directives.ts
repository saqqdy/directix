/** Get directive by name */
export function getDirective(name: string): DirectiveMeta | undefined {
	return directives.find(d => d.name === name || d.name === `v-${name}`)
}

/** Get directives by category */
export function getDirectivesByCategory(category: string): DirectiveMeta[] {
	return directives.filter(d => d.category === category)
}
